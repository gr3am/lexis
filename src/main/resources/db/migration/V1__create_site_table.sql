CREATE TABLE site (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL CONSTRAINT chk_site_name_not_blank CHECK (btrim(name) <> ''),
    root_url TEXT NOT NULL,
    root_key TEXT UNIQUE NOT NULL
        CONSTRAINT chk_site_root_key_byte_length CHECK (octet_length(root_key) <= 1024),
    operation_state VARCHAR(32) NOT NULL DEFAULT 'IDLE'
        CONSTRAINT chk_site_operation_state CHECK (operation_state IN ('IDLE', 'FULL_INDEXING', 'PAGE_INDEXING', 'DELETING')),
    deletion_requested BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
